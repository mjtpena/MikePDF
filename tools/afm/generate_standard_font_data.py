"""Generates src/MikePDF.Markup/Fonts/StandardFontData.g.cs from Adobe's AFM files of the 14 standard fonts.

Usage: python tools/afm/generate_standard_font_data.py <directory with the AFM files> <output .cs file>

The AFM files are Adobe's published metrics of the base-14 fonts (the Core 14 set; Symbol and ZapfDingbats are not used). The widths are facts
about the fonts. The files used when the table was made are the ones Adobe published with the licence "may be used, copied, and distributed for any
purpose and without charge ... provided that all copyright notices are included", taken from a copy that ships with matplotlib
(matplotlib/mpl-data/fonts/afm): phvr8a, phvb8a, phvro8a, phvbo8a (Helvetica), ptmr8a, ptmb8a, ptmri8a, ptmbi8a (Times) and pcrr8a, pcrb8a, pcrro8a,
pcrbo8a (Courier). They are not shipped with MikePDF; only the numbers are.

The table is indexed by WinAnsiEncoding code 32 to 255 (the PDF encoding, ISO 32000-1 annex D.2: Windows-1252, with the five unused codes drawing a
bullet and the no-break space and soft hyphen drawing a space and a hyphen). The Euro sign is not in the 1990 files; its widths are Adobe's
(Helvetica 556, Times 500, Courier 600).
"""
import sys
from pathlib import Path

from fontTools.agl import UV2AGL

FONTS = [
    ("Helvetica", "phvr8a"),
    ("Helvetica-Bold", "phvb8a"),
    ("Helvetica-Oblique", "phvro8a"),
    ("Helvetica-BoldOblique", "phvbo8a"),
    ("Times-Roman", "ptmr8a"),
    ("Times-Bold", "ptmb8a"),
    ("Times-Italic", "ptmri8a"),
    ("Times-BoldItalic", "ptmbi8a"),
    ("Courier", "pcrr8a"),
    ("Courier-Bold", "pcrb8a"),
    ("Courier-Oblique", "pcrro8a"),
    ("Courier-BoldOblique", "pcrbo8a"),
]

EURO = {"Helvetica": 556, "Times": 500, "Courier": 600}


def parse(path):
    widths, header = {}, {}
    for line in path.read_text(encoding="latin-1").splitlines():
        if line.startswith("C "):
            parts = [p.strip() for p in line.split(";")]
            wx = next(int(p.split()[1]) for p in parts if p.startswith("WX"))
            name = next(p.split()[1] for p in parts if p.startswith("N "))
            widths[name] = wx
        else:
            key, _, value = line.partition(" ")
            if key in ("Ascender", "Descender", "CapHeight", "XHeight", "ItalicAngle", "UnderlinePosition", "UnderlineThickness"):
                header[key] = float(value)
            elif key == "FontBBox":
                header[key] = [int(v) for v in value.split()]
    return widths, header


def glyph_name(code):
    if code in (0x7F, 0x81, 0x8D, 0x8F, 0x90, 0x9D):
        return "bullet"
    if code == 0xA0:
        return "space"
    if code == 0xAD:
        return "hyphen"
    char = bytes([code]).decode("cp1252")
    if code == 0x27:
        return "quotesingle"
    if code == 0x60:
        return "grave"
    if code == 0x80:
        return "Euro"
    extra = {0xB2: "twosuperior", 0xB3: "threesuperior", 0xB9: "onesuperior", 0xBC: "onequarter", 0xBD: "onehalf", 0xBE: "threequarters",
             0xB5: "mu", 0xD7: "multiply", 0xF7: "divide", 0xB1: "plusminus", 0xB0: "degree", 0xAC: "logicalnot", 0xA6: "brokenbar"}
    if code in extra:
        return extra[code]
    return UV2AGL[ord(char)]


def main():
    source, target = Path(sys.argv[1]), Path(sys.argv[2])
    out = []
    out.append("// <auto-generated>")
    out.append("// Generated by tools/afm/generate_standard_font_data.py from Adobe's AFM files of the standard 14 fonts. Do not edit.")
    out.append("// </auto-generated>")
    out.append("namespace MikePDF.Markup.Fonts;")
    out.append("")
    out.append("/// <summary>Advance widths (1/1000 em) for WinAnsi codes 32 to 255, and the vertical metrics, of the 12 base fonts that are not symbolic (free-text 3.2).</summary>")
    out.append("internal static class StandardFontData")
    out.append("{")
    out.append("    public static readonly string[] Names =")
    out.append("    [")
    for name, _ in FONTS:
        out.append(f'        "{name}",')
    out.append("    ];")
    out.append("")
    out.append("    /// <summary>Ascender, descender (negative), cap height, x height, italic angle, bbox left, bottom, right, top; per font in <see cref=\"Names\"/> order.</summary>")
    out.append("    public static readonly double[][] Vertical =")
    out.append("    [")
    tables = []
    for name, stem in FONTS:
        widths, header = parse(source / f"{stem}.afm")
        family = name.split("-")[0]
        row = []
        for code in range(32, 256):
            g = glyph_name(code)
            if g == "Euro":
                w = EURO[family]
            else:
                w = widths[g]
            row.append(w)
        tables.append(row)
        bbox = header["FontBBox"]
        out.append(
            "        [{asc}, {desc}, {cap}, {xh}, {ital}, {l}, {b}, {r}, {t}],".format(
                asc=int(header["Ascender"]), desc=int(header["Descender"]), cap=int(header["CapHeight"]), xh=int(header["XHeight"]),
                ital=int(header["ItalicAngle"]), l=bbox[0], b=bbox[1], r=bbox[2], t=bbox[3],
            )
        )
    out.append("    ];")
    out.append("")
    out.append("    /// <summary>Widths for codes 32 to 255, per font in <see cref=\"Names\"/> order.</summary>")
    out.append("    public static readonly ushort[][] Widths =")
    out.append("    [")
    for row in tables:
        for start in range(0, len(row), 16):
            chunk = row[start:start + 16]
            prefix = "        [" if start == 0 else "         "
            suffix = "]," if start + 16 >= len(row) else ""
            out.append(prefix + ", ".join(str(v) for v in chunk) + ("," if not suffix else "") + suffix)
    out.append("    ];")
    out.append("}")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


main()
