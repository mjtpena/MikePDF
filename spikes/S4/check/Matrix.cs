using System.Text;
using System.Text.Json;

namespace S4;

/// <summary>Turns results.json into out/matrix.md (the raw matrix the report is written from).</summary>
public static class Matrix
{
    const string NM = "not measured";

    static string B(bool? v) => v == null ? "n/a" : v.Value ? "yes" : "NO";
    static bool? GB(JsonElement e, string k) => e.TryGetProperty(k, out var v) && (v.ValueKind == JsonValueKind.True || v.ValueKind == JsonValueKind.False) ? v.GetBoolean() : null;
    static string GS(JsonElement e, string k) => e.TryGetProperty(k, out var v) && v.ValueKind == JsonValueKind.String ? v.GetString()! : "";
    static int? GI(JsonElement e, string k) => e.TryGetProperty(k, out var v) && v.ValueKind == JsonValueKind.Number ? v.GetInt32() : null;

    static string Vis(JsonElement m, string px, string inRect, int minPx = 40)
    {
        var tot = GI(m, px);
        if (tot == null) return NM;
        int? inr = GI(m, inRect);
        int n = inr ?? tot.Value;
        return (n >= minPx ? "visible" : "INVISIBLE") + $" ({n}px)";
    }

    public static void Write(string outDir, Dictionary<string, object?> unused)
    {
        var res = JsonDocument.Parse(File.ReadAllText(Path.Combine(outDir, "results.json"))).RootElement;
        var sb = new StringBuilder();
        sb.AppendLine($"# S4 raw matrix (generated by check; qpdf {res.GetProperty("qpdf").GetString()}, pdf.js {res.GetProperty("pdfjs").GetString()})");
        sb.AppendLine();
        sb.AppendLine("Acrobat and Edge columns: not measured (manual pass pending). Chrome renders with PDFium, so its column duplicates the PDFium column and is not measured separately here. \"visible\" means >= 40 changed pixels (within the annotation rect for annotations) against a render of the unmodified input by the same engine.");
        sb.AppendLine();

        void Header(string title, string cols)
        {
            sb.AppendLine($"## {title}");
            sb.AppendLine();
            var parts = cols.Split('|');
            sb.AppendLine("| " + string.Join(" | ", parts) + " |");
            sb.AppendLine("|" + string.Join("|", parts.Select(_ => "---")) + "|");
        }

        foreach (var (grp, title) in new[] { ("annot", "Annotations created through the PDFium API"), ("annot-quire", "Annotations authored by Quire (raw incremental update)") })
        {
            Header(title, "Case|Save|qpdf --check|/AP on annotation|/AP kind|Annot dict direct in /Annots|NeedAppearances|Props after PDFium reopen|PDFium render (FPDF_ANNOT)|pdf.js render|Acrobat|Edge|Orig bytes are prefix");
            foreach (var c in res.GetProperty("cases").EnumerateArray().Where(c => c.GetProperty("group").GetString() == grp))
            {
                string id = c.GetProperty("id").GetString()!, t = c.GetProperty("title").GetString()!;
                var modes = c.GetProperty("modes");
                if (!modes.EnumerateObject().Any())
                {
                    sb.AppendLine($"| {id} {t} | - | not creatable by the API | - | - | - | - | - | - | - | - | - | - |");
                    continue;
                }
                foreach (var mo in modes.EnumerateObject())
                {
                    var m = mo.Value;
                    string failed = m.TryGetProperty("reopenFailed", out var rf) ? string.Join("; ", rf.EnumerateArray().Select(x => x.GetString())) : "";
                    sb.AppendLine($"| {id} {t} | {mo.Name} | {GS(m, "qpdfVerdict")} | {B(GB(m, "apPresent"))} | {GS(m, "apKind")} | {B(GB(m, "directDict"))} | {GS(m, "needAppearances")} | {(GB(m, "reopenOk") == true ? "all ok" : "FAIL: " + failed)} | {Vis(m, "pdfiumChangedPx", "pdfiumChangedInRect")} | {Vis(m, "pdfjsChangedPx", "pdfjsChangedInRect")} | {NM} | {NM} | {B(GB(m, "inputIsExactPrefix"))} |");
                }
            }
            sb.AppendLine();
        }

        Header("AcroForm fields", "Case|Save|qpdf --check|/V correct in file|Widget AP regenerated / correct|NeedAppearances|Props after PDFium reopen|PDFium render (FFLDraw)|pdf.js render|Acrobat|Edge|Orig bytes are prefix");
        foreach (var c in res.GetProperty("cases").EnumerateArray().Where(c => c.GetProperty("group").GetString() == "form"))
        {
            string id = c.GetProperty("id").GetString()!, t = c.GetProperty("title").GetString()!;
            foreach (var mo in c.GetProperty("modes").EnumerateObject())
            {
                var m = mo.Value;
                var props = m.GetProperty("props").EnumerateArray().ToList();
                bool vOk = props.Where(p => p.GetProperty("Name").GetString()!.StartsWith("/V") || p.GetProperty("Name").GetString()!.StartsWith("/AS")).All(p => p.GetProperty("Ok").GetBoolean());
                var apProp = props.FirstOrDefault(p => p.GetProperty("Name").GetString()!.Contains("AP"));
                string ap = apProp.ValueKind == JsonValueKind.Undefined ? "n/a (state-based)" : apProp.GetProperty("Ok").GetBoolean() ? "yes" : "NO";
                string failed = string.Join("; ", m.GetProperty("reopenFailed").EnumerateArray().Select(x => x.GetString()));
                sb.AppendLine($"| {id} {t} | {mo.Name} | {GS(m, "qpdfVerdict")} | {(vOk ? "yes" : "NO")} | {ap} | {GS(m, "needAppearances")} | {(GB(m, "reopenOk") == true ? "all ok" : "FAIL: " + failed)} | {Vis(m, "pdfiumChangedPx", "pdfiumChangedInRect", 20)} | {Vis(m, "pdfjsChangedPx", "pdfjsChangedInRect", 20)} | {NM} | {NM} | {B(GB(m, "inputIsExactPrefix"))} |");
            }
        }
        sb.AppendLine();

        Header("Signature preservation (pre-signed fixtures, self-signed RSA-2048 / SHA-256 adbe.pkcs7.detached)", "Case|Save|qpdf --check|Orig bytes are prefix|Sig count before/after|ByteRange unchanged|Contents unchanged|CMS verifies (original ByteRange over new file)|CMS verifies (ByteRange as written in new file)|Acrobat");
        foreach (var c in res.GetProperty("cases").EnumerateArray().Where(c => c.GetProperty("group").GetString() == "sig"))
        {
            string id = c.GetProperty("id").GetString()!, t = c.GetProperty("title").GetString()!;
            foreach (var mo in c.GetProperty("modes").EnumerateObject())
            {
                var m = mo.Value;
                sb.AppendLine($"| {id} {t} | {mo.Name} | {GS(m, "qpdfVerdict")} | {B(GB(m, "inputIsExactPrefix"))} | {GI(m, "sigCountBefore")}/{GI(m, "sigCountAfter")} | {B(GB(m, "byteRangeUnchanged"))} | {B(GB(m, "contentsUnchanged"))} | {B(GB(m, "cmsVerifiesOriginalRange"))} | {B(GB(m, "cmsVerifiesWrittenRange"))} | {NM} |");
            }
        }
        File.WriteAllText(Path.Combine(outDir, "matrix.md"), sb.ToString());
    }
}

/// <summary>Compact one-row-per-case matrix used by the report.</summary>
public static class MatrixCompact
{
    static readonly Dictionary<string, int> Tally = new() { ["pass"] = 0, ["warn"] = 0, ["fail"] = 0, ["not measured"] = 0, ["n/a"] = 0 };
    static readonly Dictionary<string, Dictionary<string, int>> ByTable = new();
    static string curTable = "";
    static string T(string cell)
    {
        if (cell.StartsWith("yes (direct)") || cell.StartsWith("no (indirect)")) return cell;   // informational column, not a verdict
        string k;
        if (cell == "-" || cell.StartsWith("n/a")) k = "n/a";
        else if (cell.StartsWith("not measured")) k = "not measured";
        else if (cell.Contains("FAIL") || cell.Contains("INVISIBLE") || cell.StartsWith("NO") || cell.Contains("NOT ") || cell.Contains("(NO)") || cell.Contains("/ NO") || cell.Contains("NO /")) k = "fail";
        else if (cell.Contains("warn")) k = "warn";
        else k = "pass";
        Tally[k]++;
        if (!ByTable.TryGetValue(curTable, out var d)) ByTable[curTable] = d = new() { ["pass"] = 0, ["warn"] = 0, ["fail"] = 0, ["not measured"] = 0, ["n/a"] = 0 };
        d[k]++;
        return cell;
    }
    const string NM = "not measured";
    static JsonElement? M(JsonElement c, string mode) => c.GetProperty("modes").TryGetProperty(mode, out var m) ? m : null;
    static string Pair(string a, string b) => a == b ? a : a + " / " + b;
    static string V(JsonElement? m, string k) => m != null && m.Value.TryGetProperty(k, out var v) ? (v.ValueKind == JsonValueKind.String ? v.GetString()! : v.ToString()) : "-";
    static bool? Bo(JsonElement? m, string k) => m != null && m.Value.TryGetProperty(k, out var v) && (v.ValueKind == JsonValueKind.True || v.ValueKind == JsonValueKind.False) ? v.GetBoolean() : null;
    static string YN(bool? v) => v == null ? "n/a" : v.Value ? "yes" : "NO";
    static int? I(JsonElement? m, string k) => m != null && m.Value.TryGetProperty(k, out var v) && v.ValueKind == JsonValueKind.Number ? v.GetInt32() : null;
    static string Vis(JsonElement? m, string tot, string inr, int min = 40, bool expectUnchanged = false)
    {
        if (m == null) return "-";
        var t = I(m, tot); if (t == null) return NM;
        int n = I(m, inr) ?? t.Value;
        if (expectUnchanged) return n == 0 ? "unchanged (as expected)" : $"changed ({n}px)";
        return n >= min ? $"visible ({n}px)" : "INVISIBLE";
    }
    static string QP(JsonElement? m) => m == null ? "-" : V(m, "qpdfVerdict") switch { "pass" => "pass", "pass-with-warnings" => "warn", "FAIL" => "FAIL", var x => x };
    static string Reopen(JsonElement? m)
    {
        if (m == null) return "-";
        if (Bo(m, "reopenOk") == true) return "all ok";
        if (!m.Value.TryGetProperty("reopenFailed", out var rf)) return "-";
        return "FAIL: " + string.Join("; ", rf.EnumerateArray().Select(x => x.GetString()));
    }

    static void Row(StringBuilder sb, string table, string label, params string[] cells)
    {
        curTable = table;
        foreach (var c in cells) T(c);
        sb.AppendLine("| " + label + " | " + string.Join(" | ", cells) + " |");
    }

    public static void Write(string outDir)
    {
        var res = JsonDocument.Parse(File.ReadAllText(Path.Combine(outDir, "results.json"))).RootElement;
        var sb = new StringBuilder();
        sb.AppendLine("### Annotations (one row per case; \"cold\" = saved without rendering the page first, \"rendered\" = the page was rendered by PDFium before the save)");
        sb.AppendLine();
        sb.AppendLine("| Case | qpdf --check inc / full | /AP in file, cold | /AP in file, rendered | Annot dict direct in /Annots | Props after PDFium reopen | PDFium render | pdf.js cold | pdf.js rendered | Orig bytes = prefix (inc) | Acrobat | Edge |");
        sb.AppendLine("|---|---|---|---|---|---|---|---|---|---|---|---|");
        foreach (var c in res.GetProperty("cases").EnumerateArray().Where(c => c.GetProperty("group").GetString() is "annot" or "annot-quire"))
        {
            string id = c.GetProperty("id").GetString()!, t = c.GetProperty("title").GetString()!;
            var inc = M(c, "inc"); var full = M(c, "full"); var incR = M(c, "incR");
            if (inc == null) { sb.AppendLine($"| {id} {t} | n/a: PDFium cannot create it (FPDFAnnot_IsSupportedSubtype = 0, FPDFPage_CreateAnnot = NULL) | - | - | - | - | - | - | - | - | - | - |"); curTable = "annotations"; T("n/a"); continue; }
            bool q = c.GetProperty("group").GetString() == "annot-quire";
            string direct = YN(Bo(inc, "directDict"));
            Row(sb, "annotations", $"{id} {t}",
                $"{QP(inc)} / {QP(full)}",
                YN(Bo(inc, "apPresent")),
                incR == null ? (q ? "n/a (not PDFium-built)" : "-") : YN(Bo(incR, "apPresent")),
                direct == "yes" ? "yes (direct)" : "no (indirect)",
                Reopen(inc),
                Vis(inc, "pdfiumChangedPx", "pdfiumChangedInRect"),
                Vis(inc, "pdfjsChangedPx", "pdfjsChangedInRect"),
                incR == null ? "-" : Vis(incR, "pdfjsChangedPx", "pdfjsChangedInRect"),
                YN(Bo(inc, "inputIsExactPrefix")), NM, NM);
        }
        sb.AppendLine();
        sb.AppendLine("### AcroForm fields");
        sb.AppendLine();
        sb.AppendLine("| Case | qpdf --check inc / full | /V (or /AS) correct in file | Widget /AP | NeedAppearances | Props after PDFium reopen | PDFium render (FFLDraw) | pdf.js render | Orig bytes = prefix (inc) | Acrobat | Edge |");
        sb.AppendLine("|---|---|---|---|---|---|---|---|---|---|---|");
        foreach (var c in res.GetProperty("cases").EnumerateArray().Where(c => c.GetProperty("group").GetString() == "form"))
        {
            string id = c.GetProperty("id").GetString()!, t = c.GetProperty("title").GetString()!;
            var inc = M(c, "inc")!; var full = M(c, "full");
            var props = inc.Value.GetProperty("props").EnumerateArray().ToList();
            bool vOk = props.Where(p => p.GetProperty("Name").GetString()!.StartsWith("/V") || p.GetProperty("Name").GetString()!.StartsWith("/AS") || p.GetProperty("Name").GetString()!.StartsWith("no /V")).All(p => p.GetProperty("Ok").GetBoolean());
            var apProp = props.FirstOrDefault(p => p.GetProperty("Name").GetString()!.Contains("AP"));
            string ap = apProp.ValueKind == JsonValueKind.Undefined
                ? (Bo(inc, "inputHadAp") != true ? "generated by PDFium (input had no AP)" : Bo(inc, "apChangedVsInput") == true ? "state stream re-generated by PDFium (differs from the author's)" : "original state streams reused")
                : apProp.GetProperty("Ok").GetBoolean() ? (id == "B09" ? "unchanged (as expected)" : "regenerated, shows value") : "NOT regenerated";
            bool unchanged = id == "B09";
            Row(sb, "forms", $"{id} {t}", $"{QP(inc)} / {QP(full)}", YN(vOk), ap, V(inc, "needAppearances") == "absent" ? "absent (not set)" : V(inc, "needAppearances"), Reopen(inc),
                Vis(inc, "pdfiumChangedPx", "pdfiumChangedInRect", 20, unchanged), Vis(inc, "pdfjsChangedPx", "pdfjsChangedInRect", 20, unchanged), YN(Bo(inc, "inputIsExactPrefix")), NM, NM);
        }
        sb.AppendLine();
        sb.AppendLine("### Signature preservation (fixtures signed with a throw-away self-signed RSA-2048 / SHA-256, adbe.pkcs7.detached)");
        sb.AppendLine();
        sb.AppendLine("| Case | Save | qpdf --check | Orig bytes = prefix | Sig count before/after | Sig dict /ByteRange and /Contents unchanged | CMS verifies (signature-only) with the ORIGINAL ByteRange over the new file | Acrobat |");
        sb.AppendLine("|---|---|---|---|---|---|---|---|");
        foreach (var c in res.GetProperty("cases").EnumerateArray().Where(c => c.GetProperty("group").GetString() == "sig"))
        {
            string id = c.GetProperty("id").GetString()!, t = c.GetProperty("title").GetString()!;
            foreach (var mo in c.GetProperty("modes").EnumerateObject())
            {
                var m = (JsonElement?)mo.Value;
                bool same = I(m, "sigCountBefore") == I(m, "sigCountAfter") && I(m, "sigCountAfter") == 1;
                string cms = YN(Bo(m, "cmsVerifiesOriginalRange"));
                // a full copy is EXPECTED to break the signature (bytes move); report it as a fail for "preserved"
                Row(sb, "signatures", $"{id} {t} | {mo.Name}", QP(m), YN(Bo(m, "inputIsExactPrefix")), same ? $"{I(m, "sigCountBefore")}/{I(m, "sigCountAfter")}" : "FAIL " + I(m, "sigCountBefore") + "/" + I(m, "sigCountAfter"),
                    YN(Bo(m, "byteRangeUnchanged") == true && Bo(m, "contentsUnchanged") == true), cms, NM);
            }
        }
        sb.AppendLine();
        sb.AppendLine("### Cell tally (every cell of the three tables above except the case label)");
        sb.AppendLine();
        sb.AppendLine("| Table | pass | warn | fail | not measured | n/a |");
        sb.AppendLine("|---|---|---|---|---|---|");
        foreach (var (k, d) in ByTable) sb.AppendLine($"| {k} | {d["pass"]} | {d["warn"]} | {d["fail"]} | {d["not measured"]} | {d["n/a"]} |");
        sb.AppendLine($"| **total** | {Tally["pass"]} | {Tally["warn"]} | {Tally["fail"]} | {Tally["not measured"]} | {Tally["n/a"]} |");
        File.WriteAllText(Path.Combine(outDir, "matrix-compact.md"), sb.ToString());
    }
}
